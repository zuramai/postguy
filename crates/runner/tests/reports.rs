use std::io::{Cursor, Read};

use postguy_model::{Id, ScriptFailure, ScriptPhase, TestKind, TestResult, TestStatus};
use postguy_runner::report::{self, Cell, RowStatus};
use postguy_runner::{IterationResult, RequestRun, RunResult, Totals};

const OFFSET: i32 = 25_200;

fn test(name: &str, status: TestStatus, kind: TestKind, message: Option<&str>) -> TestResult {
    TestResult { name: name.into(), status, message: message.map(Into::into), phase: ScriptPhase::PostResponse, kind }
}

fn run(name: &str) -> RequestRun {
    RequestRun {
        request_id: Id(name.into()),
        name: name.into(),
        path: vec!["Users".into(), "Admin".into()],
        method: "POST".into(),
        url: "https://x.test/a".into(),
        status: Some(200),
        duration_ms: 120,
        size_bytes: 512,
        tests: Vec::new(),
        failures: Vec::new(),
        error: None,
        skipped: None,
        started_ms: 1_700_000_000_000,
        report: serde_json::Map::new(),
        response_excerpt: None,
    }
}

fn sample() -> RunResult {
    let mut passing = run("login");
    passing.tests =
        vec![test("res.status eq 200", TestStatus::Passed, TestKind::Assertion, None), test("ok", TestStatus::Passed, TestKind::Test, None)];
    passing.report.insert("subject_id".into(), serde_json::json!("s1"));
    let mut failing = run("=cmd(1)");
    failing.tests = vec![test("res.n eq 2", TestStatus::Failed, TestKind::Assertion, Some("expected 2, got 3"))];
    failing.failures = vec![ScriptFailure { phase: ScriptPhase::PostResponse, origin: "request x".into(), message: "boom".into(), line: Some(4) }];
    failing.response_excerpt = Some("<b>\"bad\" & \u{1}</b>".into());
    failing.report.insert("score".into(), serde_json::json!(0.5));
    failing.report.insert("subject_id".into(), serde_json::json!("s2"));
    let mut errored = run("down");
    errored.status = None;
    errored.error = Some("connection refused".into());
    let mut skipped = run("later");
    skipped.skipped = Some("skipRequest()".into());
    let mut totals = Totals::default();
    let requests = vec![passing, failing, errored, skipped];
    for r in &requests {
        totals.add(r);
    }
    RunResult {
        id: "run1".into(),
        collection_id: Id("c".into()),
        collection_name: "Face (QA)".into(),
        environment_name: Some("staging".into()),
        started_ms: 1_700_000_000_000,
        finished_ms: 1_700_000_002_500,
        iterations: vec![IterationResult { index: 0, requests, warnings: Vec::new() }],
        totals,
        ..RunResult::default()
    }
}

fn zip_part(bytes: &[u8], name: &str) -> String {
    let mut archive = zip::ZipArchive::new(Cursor::new(bytes)).expect("zip");
    let mut file = archive.by_name(name).unwrap_or_else(|err| panic!("{name}: {err}"));
    let mut text = String::new();
    file.read_to_string(&mut text).expect("utf8");
    text
}

#[test]
fn table_has_the_documented_columns_and_summary() {
    let table = report::table(&sample(), OFFSET);
    let labels: Vec<&str> = table.summary.iter().map(|(label, _)| label.as_str()).collect();
    assert_eq!(
        labels,
        [
            "Collection",
            "Folder",
            "Environment",
            "Started at",
            "Finished at",
            "Duration",
            "Iterations",
            "Requests",
            "Passed",
            "Failed",
            "Errors",
            "Skipped",
            "Pass rate",
            "Assertions",
            "Tests",
            "Average response time",
            "Stopped",
            "Generated by"
        ]
    );
    let value = |label: &str| table.summary.iter().find(|(l, _)| l == label).map(|(_, v)| v.clone()).expect(label);
    assert_eq!(value("Folder"), "All");
    assert_eq!(value("Started at"), "2023-11-15 05:13:20 +07:00");
    assert_eq!((value("Passed").as_str(), value("Failed").as_str(), value("Errors").as_str(), value("Skipped").as_str()), ("1", "1", "1", "1"));
    assert_eq!(value("Pass rate"), "33.3%");
    assert_eq!(value("Assertions"), "1 / 2");
    assert_eq!(value("Tests"), "1 / 1");
    assert_eq!(value("Stopped"), "No");
    assert_eq!(table.request_headers.len(), 19, "17 fixed + 2 custom");
    assert_eq!(&table.request_headers[17..], ["subject_id", "score"], "first-appearance order");
    assert_eq!(table.test_headers, ["#", "Iteration", "Folder", "Request", "Kind", "Name", "Status", "Message"]);
    let results: Vec<String> = table.requests.iter().map(|(_, row)| row[7].text()).collect();
    assert_eq!(results, ["PASS", "FAIL", "ERROR", "SKIPPED"]);
    assert_eq!(table.requests[1].0, RowStatus::Fail);
    assert_eq!(table.requests[1].1[2], Cell::Text("Users / Admin".into()));
    assert_eq!(table.requests[1].1[15].text(), "[FAIL] res.n eq 2: expected 2, got 3\n[SCRIPT] post-response request x line 4: boom");
    assert_eq!(table.requests[2].1[15].text(), "[ERROR] connection refused");
    assert_eq!(table.requests[1].1[18], Cell::Float(0.5));
    assert_eq!(table.requests[0].1[18], Cell::Empty);
    assert_eq!(table.tests.len(), 3);
    assert_eq!(table.tests[0].1[4], Cell::Text("Assertion".into()));
    assert_eq!(table.tests[1].1[4], Cell::Text("Test".into()));
    assert_eq!(table.tests[2].1[6], Cell::Text("FAILED".into()));
}

#[test]
fn csv_has_bom_crlf_quoting_and_formula_guard() {
    let bytes = report::csv(&report::table(&sample(), OFFSET));
    assert_eq!(&bytes[..3], [0xEF, 0xBB, 0xBF]);
    let text = String::from_utf8(bytes[3..].to_vec()).expect("utf8");
    assert!(text.starts_with("#,Iteration,Folder,Request,"), "{text}");
    assert!(text.contains("'=cmd(1)"), "formula guard");
    assert!(text.contains("\"[FAIL] res.n eq 2: expected 2, got 3\n[SCRIPT]"), "multi-line fields are quoted");
    assert!(text.contains("\"<b>\"\"bad\"\" & "), "quotes doubled");
    assert!(text.split("\r\n").count() > 4 && !text.replace("\r\n", "").contains('\r'));
}

#[test]
fn xlsx_is_a_valid_package_with_three_sheets() {
    let bytes = report::xlsx(&report::table(&sample(), OFFSET)).expect("xlsx");
    let workbook = zip_part(&bytes, "xl/workbook.xml");
    for name in ["Summary", "Requests", "Tests"] {
        assert!(workbook.contains(&format!("name=\"{name}\"")), "{workbook}");
    }
    assert_eq!(workbook.matches("_xlnm._FilterDatabase").count(), 2);
    for part in
        ["[Content_Types].xml", "_rels/.rels", "xl/_rels/workbook.xml.rels", "xl/styles.xml", "xl/worksheets/sheet1.xml", "xl/worksheets/sheet3.xml"]
    {
        zip_part(&bytes, part);
    }
    let styles = zip_part(&bytes, "xl/styles.xml");
    assert!(styles.contains("FFE5E7EB") && styles.contains("FFDCFCE7") && styles.contains("FFFEE2E2") && styles.contains("FFFEF3C7"));
    let requests = zip_part(&bytes, "xl/worksheets/sheet2.xml");
    assert!(requests.contains("<pane ySplit=\"1\" topLeftCell=\"A2\"") && requests.contains("state=\"frozen\""));
    assert!(requests.contains("<autoFilter ref=\"A1:S5\"/>"), "{requests}");
    assert!(requests.contains("t=\"inlineStr\""));
    assert!(requests.contains("&lt;b&gt;&quot;bad&quot; &amp; &lt;/b&gt;"), "escaped and control char stripped: {requests}");
    assert!(requests.contains("<c r=\"H3\" s=\"3\" t=\"inlineStr\">"), "FAIL cell is styled");
    assert!(requests.contains("<c r=\"H2\" s=\"2\""));
    assert!(requests.contains("<c r=\"H5\" s=\"4\""));
    let tests = zip_part(&bytes, "xl/worksheets/sheet3.xml");
    assert!(tests.contains("FAILED"));
    assert!(zip_part(&bytes, "xl/worksheets/sheet1.xml").contains("Face (QA)"));
}

#[test]
fn xlsx_truncates_long_text() {
    let mut result = sample();
    result.iterations[0].requests[0].response_excerpt = Some("a".repeat(40_000));
    let bytes = report::xlsx(&report::table(&result, OFFSET)).expect("xlsx");
    let sheet = zip_part(&bytes, "xl/worksheets/sheet2.xml");
    assert!(sheet.contains(&"a".repeat(32_767)) && !sheet.contains(&"a".repeat(32_768)));
}

fn big(rows: usize) -> RunResult {
    let mut result = sample();
    result.iterations[0].requests = (0..rows).map(|i| run(&format!("request {i}"))).collect();
    result
}

#[test]
fn pdf_structure_is_valid() {
    let result = big(300);
    let bytes = report::pdf(&report::table(&result, OFFSET));
    assert!(bytes.starts_with(b"%PDF-1.4"));
    assert!(bytes.ends_with(b"%%EOF\n"));
    let text = String::from_utf8_lossy(&bytes).into_owned();
    let xref_at = text.rfind("startxref\n").expect("startxref");
    let xref_offset: usize = text[xref_at + 10..].lines().next().expect("offset").parse().expect("number");
    assert!(bytes[xref_offset..].starts_with(b"xref\n"));
    let tail = String::from_utf8_lossy(&bytes[xref_offset..]).into_owned();
    let table = tail.as_str();
    let mut lines = table.lines();
    lines.next();
    let header = lines.next().expect("subsection");
    let count: usize = header.split(' ').nth(1).expect("count").parse().expect("n");
    lines.next(); // free entry
    for id in 1..count {
        let entry = lines.next().expect("entry");
        assert_eq!(entry.len(), 19, "{entry:?}");
        let offset: usize = entry[..10].parse().expect("offset");
        assert!(bytes[offset..].starts_with(format!("{id} 0 obj").as_bytes()), "object {id}");
    }
    let pages = text.matches("/Type /Page ").count();
    assert!((6..=12).contains(&pages), "300 rows span a few landscape pages, got {pages}");
    assert!(text.contains(&format!("/Count {pages}")));
    assert!(text.contains(&format!("Page 1 of {pages}")) && text.contains(&format!("Page {pages} of {pages}")));
    assert!(text.contains("/BaseFont /Courier-Bold") && !text.contains("/FontFile"));
    assert!(text.matches("(Failure details)").count() >= pages, "header repeats on every page");
}

#[test]
fn pdf_escapes_and_substitutes_text() {
    let mut result = sample();
    result.iterations[0].requests[0].name = "a (b) \\ 日本 é…".into();
    let bytes = report::pdf(&report::table(&result, OFFSET));
    let text = String::from_utf8_lossy(&bytes).into_owned();
    assert!(text.contains("a \\(b\\) \\\\ ?? \\351\\205"), "{}", text.lines().filter(|l| l.contains("Users")).collect::<String>());
}

