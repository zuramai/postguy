//! OAuth 2.0 protocol pieces (RFC 6749/7636): authorization URL, PKCE, token request forms and
//! token response parsing. Networking and the loopback listener live in the engine so this crate
//! stays pure and testable.

use std::collections::BTreeMap;

use postguy_model::auth::{OAuth2Auth, OAuth2ClientAuthentication, OAuth2Grant, PkceMethod};
use serde::Deserialize;
use sha2::{Digest as _, Sha256};

use crate::error::{Result, invalid, missing};
use crate::util::{b64url, pct};

/// A token endpoint response (success or OAuth error).
#[derive(Debug, Clone, PartialEq, Eq, Default, Deserialize)]
pub struct TokenResponse {
    #[serde(default)]
    pub access_token: String,
    #[serde(default)]
    pub token_type: String,
    #[serde(default)]
    pub expires_in: Option<u64>,
    #[serde(default)]
    pub refresh_token: String,
    #[serde(default)]
    pub scope: String,
    #[serde(default)]
    pub error: String,
    #[serde(default)]
    pub error_description: String,
}

impl TokenResponse {
    pub fn is_error(&self) -> bool {
        !self.error.is_empty()
    }

    pub fn message(&self) -> String {
        if self.error.is_empty() {
            "the token endpoint returned no access token".into()
        } else if self.error_description.is_empty() {
            self.error.clone()
        } else {
            format!("{}: {}", self.error, self.error_description)
        }
    }
}

/// Parse a token endpoint JSON body (application/json or form-encoded tolerant).
pub fn parse_token_response(status: u16, body: &[u8]) -> Result<TokenResponse> {
    let text = std::str::from_utf8(body).map_err(|_| invalid("oauth2", "token response is not UTF-8"))?;
    let token: TokenResponse = serde_json::from_str(text)
        .or_else(|_| {
            // Some servers answer form-encoded despite the spec.
            let mut map = BTreeMap::new();
            for pair in text.split('&') {
                let (key, value) = pair.split_once('=').unwrap_or((pair, ""));
                map.insert(crate::util::form_decode(key), crate::util::form_decode(value));
            }
            let json = serde_json::json!({
                "access_token": map.get("access_token").cloned().unwrap_or_default(),
                "token_type": map.get("token_type").cloned().unwrap_or_default(),
                "refresh_token": map.get("refresh_token").cloned().unwrap_or_default(),
                "expires_in": map.get("expires_in").and_then(|value| value.parse::<u64>().ok()),
                "scope": map.get("scope").cloned().unwrap_or_default(),
                "error": map.get("error").cloned().unwrap_or_default(),
                "error_description": map.get("error_description").cloned().unwrap_or_default(),
            });
            serde_json::from_value(json).map_err(|err| serde_json::Error::io(std::io::Error::other(err)))
        })
        .map_err(|err| invalid("oauth2", format!("token response is not JSON: {err}")))?;
    if !(200..300).contains(&status) && token.error.is_empty() {
        return Err(invalid("oauth2", format!("token endpoint returned HTTP {status}")));
    }
    if token.access_token.is_empty() && token.error.is_empty() {
        return Err(invalid("oauth2", "token endpoint returned no access token"));
    }
    Ok(token)
}

/// Build the browser authorization URL. `state` and the PKCE verifier are generated by the
/// caller so the loopback listener can verify the callback.
pub fn authorize_url(auth: &OAuth2Auth, redirect_uri: &str, state: &str, pkce_challenge: Option<&str>) -> Result<String> {
    if auth.auth_url.trim().is_empty() {
        return Err(missing("oauth2", "authorization URL"));
    }
    if auth.client_id.trim().is_empty() {
        return Err(missing("oauth2", "client ID"));
    }
    let mut params = vec![
        ("response_type".to_string(), if matches!(auth.grant_type, OAuth2Grant::Implicit) { "token" } else { "code" }.to_string()),
        ("client_id".to_string(), auth.client_id.clone()),
        ("redirect_uri".to_string(), redirect_uri.to_string()),
        ("state".to_string(), state.to_string()),
    ];
    if !auth.scope.is_empty() {
        params.push(("scope".to_string(), auth.scope.clone()));
    }
    if let Some(challenge) = pkce_challenge {
        let method = auth.pkce.as_ref().map(|pkce| pkce.method).unwrap_or_default();
        params.push(("code_challenge".to_string(), challenge.to_string()));
        params.push((
            "code_challenge_method".to_string(),
            match method {
                PkceMethod::S256 => "S256",
                PkceMethod::Plain => "plain",
            }
            .to_string(),
        ));
    }
    for extra in &auth.extra_params {
        if !extra.key.is_empty() {
            params.push((extra.key.clone(), extra.value.clone()));
        }
    }
    let separator = if auth.auth_url.contains('?') { '&' } else { '?' };
    let query = params.iter().map(|(key, value)| format!("{}={}", pct(key), pct(value))).collect::<Vec<_>>().join("&");
    Ok(format!("{}{separator}{query}", auth.auth_url))
}

/// A PKCE verifier and its challenge.
pub fn pkce(method: PkceMethod) -> Result<(String, String)> {
    let verifier = crate::random_nonce()? + &crate::random_nonce()?;
    let challenge = challenge_for(&verifier, method);
    Ok((verifier, challenge))
}

/// The challenge for an existing verifier.
pub fn challenge_for(verifier: &str, method: PkceMethod) -> String {
    match method {
        PkceMethod::S256 => b64url(&Sha256::digest(verifier.as_bytes())),
        PkceMethod::Plain => verifier.to_string(),
    }
}

/// A token request: form pairs plus an optional Authorization header.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TokenRequest {
    pub url: String,
    pub form: Vec<(String, String)>,
    pub authorization: Option<String>,
}

/// Build the token endpoint request for a grant.
pub fn token_request(auth: &OAuth2Auth, code: Option<&str>, verifier: Option<&str>) -> Result<TokenRequest> {
    if auth.token_url.trim().is_empty() {
        return Err(missing("oauth2", "token URL"));
    }
    let mut form = Vec::new();
    match auth.grant_type {
        OAuth2Grant::AuthorizationCode | OAuth2Grant::AuthorizationCodeWithPkce => {
            let code = code.ok_or_else(|| missing("oauth2", "authorization code"))?;
            form.push(("grant_type".into(), "authorization_code".into()));
            form.push(("code".into(), code.to_string()));
            form.push(("redirect_uri".into(), auth.callback_url.clone()));
            if auth.grant_type == OAuth2Grant::AuthorizationCodeWithPkce {
                let verifier = verifier.ok_or_else(|| missing("oauth2", "PKCE verifier"))?;
                form.push(("code_verifier".into(), verifier.to_string()));
            }
        }
        OAuth2Grant::PasswordCredentials => {
            if auth.username.is_empty() {
                return Err(missing("oauth2", "username"));
            }
            form.push(("grant_type".into(), "password".into()));
            form.push(("username".into(), auth.username.clone()));
            form.push(("password".into(), auth.password.clone()));
        }
        OAuth2Grant::ClientCredentials => form.push(("grant_type".into(), "client_credentials".into())),
        OAuth2Grant::Implicit => {
            return Err(invalid("oauth2", "the implicit grant returns the token in the browser redirect, not from the token endpoint"));
        }
    }
    if !auth.scope.is_empty() {
        form.push(("scope".into(), auth.scope.clone()));
    }
    for extra in &auth.extra_params {
        if !extra.key.is_empty() && matches!(extra.delivery, postguy_model::auth::OAuth2ParamDelivery::Body) {
            form.push((extra.key.clone(), extra.value.clone()));
        }
    }
    let authorization = match auth.client_authentication {
        OAuth2ClientAuthentication::BasicHeader => {
            if auth.client_id.is_empty() {
                return Err(missing("oauth2", "client ID"));
            }
            Some(format!("Basic {}", crate::util::b64std(format!("{}:{}", pct(&auth.client_id), pct(&auth.client_secret)).as_bytes())))
        }
        OAuth2ClientAuthentication::Body => {
            form.push(("client_id".into(), auth.client_id.clone()));
            if !auth.client_secret.is_empty() {
                form.push(("client_secret".into(), auth.client_secret.clone()));
            }
            None
        }
    };
    Ok(TokenRequest { url: auth.token_url.clone(), form, authorization })
}

/// Build a refresh-token request.
pub fn refresh_request(auth: &OAuth2Auth, refresh_token: &str) -> Result<TokenRequest> {
    if refresh_token.is_empty() {
        return Err(missing("oauth2", "refresh token"));
    }
    let token_url = if auth.refresh_url.trim().is_empty() { auth.token_url.trim() } else { auth.refresh_url.trim() };
    if token_url.is_empty() {
        return Err(missing("oauth2", "token URL"));
    }
    let mut form = vec![("grant_type".to_string(), "refresh_token".to_string()), ("refresh_token".to_string(), refresh_token.to_string())];
    if !auth.scope.is_empty() {
        form.push(("scope".into(), auth.scope.clone()));
    }
    let authorization = match auth.client_authentication {
        OAuth2ClientAuthentication::BasicHeader => {
            if auth.client_id.is_empty() {
                return Err(missing("oauth2", "client ID"));
            }
            Some(format!("Basic {}", crate::util::b64std(format!("{}:{}", pct(&auth.client_id), pct(&auth.client_secret)).as_bytes())))
        }
        OAuth2ClientAuthentication::Body => {
            form.push(("client_id".into(), auth.client_id.clone()));
            if !auth.client_secret.is_empty() {
                form.push(("client_secret".into(), auth.client_secret.clone()));
            }
            None
        }
    };
    Ok(TokenRequest { url: token_url.to_string(), form, authorization })
}

#[cfg(test)]
mod tests {
    use super::*;
    use postguy_model::auth::OAuth2Pkce;

    fn auth() -> OAuth2Auth {
        OAuth2Auth {
            grant_type: OAuth2Grant::AuthorizationCodeWithPkce,
            auth_url: "https://auth.example/authorize".into(),
            token_url: "https://auth.example/token".into(),
            client_id: "client".into(),
            client_secret: "secret".into(),
            callback_url: "http://127.0.0.1:7777/callback".into(),
            scope: "read write".into(),
            pkce: Some(OAuth2Pkce::default()),
            ..OAuth2Auth::default()
        }
    }

    #[test]
    fn authorize_url_contains_pkce_and_encoded_parameters() {
        let (verifier, challenge) = pkce(PkceMethod::S256).expect("OS entropy");
        assert!(!verifier.is_empty());
        let url = authorize_url(&auth(), "http://127.0.0.1:7777/callback", "state-1", Some(&challenge)).expect("url");
        assert!(url.starts_with("https://auth.example/authorize?"));
        assert!(url.contains("response_type=code"));
        assert!(url.contains("code_challenge_method=S256"));
        assert!(url.contains("scope=read%20write"));
        assert!(url.contains("state=state-1"));
    }

    #[test]
    fn token_requests_cover_grants_and_client_authentication() {
        let request = token_request(&auth(), Some("code-1"), Some("verifier")).expect("request");
        assert!(request.form.iter().any(|(key, value)| key == "grant_type" && value == "authorization_code"));
        assert!(request.form.iter().any(|(key, _)| key == "code_verifier"));
        assert!(request.authorization.is_some(), "basic client auth by default");

        let mut password = auth();
        password.grant_type = OAuth2Grant::PasswordCredentials;
        password.username = "ada".into();
        password.password = "secret".into();
        let request = token_request(&password, None, None).expect("password");
        assert!(request.form.iter().any(|(key, value)| key == "grant_type" && value == "password"));

        let mut body = auth();
        body.client_authentication = OAuth2ClientAuthentication::Body;
        let request = token_request(&body, Some("c"), Some("v")).expect("body auth");
        assert!(request.authorization.is_none());
        assert!(request.form.iter().any(|(key, _)| key == "client_secret"));

        let refresh = refresh_request(&auth(), "refresh").expect("refresh");
        assert_eq!(refresh.url, "https://auth.example/token");
        assert!(refresh.form.iter().any(|(key, value)| key == "grant_type" && value == "refresh_token"));
    }

    #[test]
    fn token_errors_and_form_responses_parse() {
        let error = parse_token_response(400, br#"{"error":"invalid_grant","error_description":"bad code"}"#).expect("parse");
        assert!(error.is_error());
        assert_eq!(error.message(), "invalid_grant: bad code");
        let form = parse_token_response(200, b"access_token=abc&token_type=Bearer&expires_in=60").expect("form");
        assert_eq!(form.access_token, "abc");
        assert_eq!(form.expires_in, Some(60));
        assert!(parse_token_response(200, br#"{"token_type":"Bearer"}"#).is_err());
    }
}
