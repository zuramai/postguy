//! `cargo xtask icons`: convert the Lucide SVGs in `assets/icons/` into path data compiled into
//! the UI (`crates/ui-egui/src/icons_gen.rs`), which the egui painter draws as 1.5 px strokes.
//! No SVG renderer ships in the release binary (PROMPT.md 4.2); this is the build-time pipeline.
//!
//! Unknown SVG elements fail loudly here rather than losing strokes silently: an icon that
//! renders as a subset of its strokes is a visual defect, so the generator refuses anything it
//! cannot translate exactly.

use std::fmt::Write as _;

use anyhow::{Context, Result, bail};

pub fn run(args: &[String]) -> Result<()> {
    let check = args.iter().any(|a| a == "--check");
    let root = crate::gates::root();
    let icons_dir = root.join("assets").join("icons");
    let mut entries: Vec<std::path::PathBuf> = std::fs::read_dir(&icons_dir)
        .with_context(|| format!("reading {}", icons_dir.display()))?
        .collect::<std::result::Result<Vec<std::fs::DirEntry>, _>>()
        .with_context(|| format!("listing {}", icons_dir.display()))?
        .into_iter()
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "svg"))
        .collect();
    entries.sort();
    if entries.is_empty() {
        bail!("no .svg files in assets/icons/; add the Lucide icons (ISC, attributed in ATTRIBUTION.toml) this project uses");
    }

    let mut icons: Vec<(String, Vec<String>)> = Vec::new();
    for file in &entries {
        let name = file.file_stem().and_then(|s| s.to_str()).context("icon file name is not UTF-8")?.to_string();
        let svg = std::fs::read_to_string(file).with_context(|| format!("reading {}", file.display()))?;
        let data = icon_path_data(&svg).with_context(|| format!("converting {}", file.display()))?;
        icons.push((name, data));
    }

    let generated = render(&icons);
    let out_path = root.join("crates").join("ui-egui").join("src").join("icons_gen.rs");
    if check {
        let current = std::fs::read_to_string(&out_path).unwrap_or_default();
        if current != generated {
            bail!("{} is out of date; run `cargo xtask icons`", out_path.display());
        }
        println!("icons: {} icons up to date", icons.len());
        return Ok(());
    }
    std::fs::write(&out_path, &generated)?;
    println!("icons: wrote {} ({} icons)", out_path.display(), icons.len());
    Ok(())
}

/// The generated module source. Zero dependencies: path-data strings only, parsed to
/// `kurbo::BezPath` at draw time (PROMPT.md 4.2).
fn render(icons: &[(String, Vec<String>)]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// Generated by `cargo xtask icons` from assets/icons/*.svg (Lucide, ISC; see ATTRIBUTION.toml).");
    let _ = writeln!(out, "// Do not edit; rerun `cargo xtask icons`.");
    let _ = writeln!(out);
    let _ = writeln!(out, "/// (icon name, path-data strings) pairs, drawn as strokes at 14-16 px. One string per");
    let _ = writeln!(out, "/// source `<path>`/primitive: relative moves inside a string anchor at that element's own");
    let _ = writeln!(out, "/// start, so strings must never be concatenated (that would rebase their moves).");
    let _ = writeln!(out, "#[rustfmt::skip]");
    let _ = writeln!(out, "pub const ICONS: &[(&str, &[&str])] = &[");
    for (name, data) in icons {
        let datas: Vec<String> = data.iter().map(|d| format!("\"{d}\"")).collect();
        let _ = writeln!(out, "    (\"{name}\", &[{}]),", datas.join(", "));
    }
    let _ = writeln!(out, "];");
    out
}

fn num(text: impl AsRef<str>) -> Result<f64> {
    text.as_ref().trim().parse::<f64>().with_context(|| format!("attribute value `{}` is not a number", text.as_ref()))
}

fn fmt(n: f64) -> String {
    format!("{n}")
}

/// Extract every drawable primitive of an SVG as its own path-data string. One entry per
/// `<path>`/primitive: each `<path>` element starts fresh, and its relative moves anchor at
/// that element's start, so the strings must be parsed separately (never concatenated).
pub fn icon_path_data(svg: &str) -> Result<Vec<String>> {
    let mut parts: Vec<String> = Vec::new();
    let mut rest = svg;
    while let Some(start) = rest.find('<') {
        let after = &rest[start + 1..];
        let Some(end) = after.find('>') else { break };
        let tag = &after[..end];
        let (name, body) = tag.split_once(|c: char| c.is_whitespace()).unwrap_or((tag, ""));
        match name.trim() {
            "path" => {
                let d = attr(body, "d").context("path without d")?;
                parts.push(d.to_string());
            }
            "circle" => {
                let cx = num(attr(body, "cx").context("circle without cx")?)?;
                let cy = num(attr(body, "cy").context("circle without cy")?)?;
                let r = num(attr(body, "r").context("circle without r")?)?;
                parts.push(circle_path(cx, cy, r));
            }
            "rect" => {
                let x = num(attr(body, "x").unwrap_or_else(|| "0".to_string()))?;
                let y = num(attr(body, "y").unwrap_or_else(|| "0".to_string()))?;
                let w = num(attr(body, "width").context("rect without width")?)?;
                let h = num(attr(body, "height").context("rect without height")?)?;
                match attr(body, "rx") {
                    Some(rx) => {
                        let rx = num(rx)?;
                        let ry = match attr(body, "ry") {
                            Some(ry) => num(ry)?,
                            None => rx,
                        };
                        parts.push(rounded_rect_path(x, y, w, h, rx, ry)?);
                    }
                    None => parts.push(rect_path(x, y, w, h)),
                }
            }
            "line" => {
                let x1 = num(attr(body, "x1").context("line without x1")?)?;
                let y1 = num(attr(body, "y1").context("line without y1")?)?;
                let x2 = num(attr(body, "x2").context("line without x2")?)?;
                let y2 = num(attr(body, "y2").context("line without y2")?)?;
                parts.push(format!("M{} {} L{} {}", fmt(x1), fmt(y1), fmt(x2), fmt(y2)));
            }
            "polyline" | "polygon" => {
                let points = attr(body, "points").context("polyline/polygon without points")?;
                let mut d = String::from("M");
                for (i, point) in points.split_whitespace().enumerate() {
                    if i > 0 {
                        let _ = write!(d, " L");
                    }
                    let Some((x, y)) = point.split_once(',') else { bail!("point `{point}` lacks a comma") };
                    let _ = write!(d, "{} {}", fmt(num(x)?), fmt(num(y)?));
                }
                if name.trim() == "polygon" {
                    d.push_str(" Z");
                }
                parts.push(d);
            }
            "svg" | "?xml" | "!--" => {}
            other if other.starts_with('/') || other.starts_with('!') => {}
            other => bail!("unsupported SVG element `<{other}>` (extend xtask/src/icons.rs rather than dropping strokes)"),
        }
        rest = &rest[start + 1 + end + 1..];
    }
    if parts.is_empty() {
        bail!("no drawable primitives found");
    }
    Ok(parts)
}

fn attr(tag: &str, name: &str) -> Option<String> {
    let pattern = format!("{name}=");
    let start = tag.find(&pattern)?;
    let after_eq = &tag[start + pattern.len()..];
    let quote = after_eq.chars().next()?;
    let after_quote = after_eq.strip_prefix(quote)?;
    let end = after_quote.find(quote)?;
    Some(after_quote[..end].to_string())
}

fn circle_path(cx: f64, cy: f64, r: f64) -> String {
    format!("M{} {} a{} {} 0 1 0 {} 0 a{} {} 0 1 0 {} 0", fmt(cx - r), fmt(cy), fmt(r), fmt(r), fmt(2.0 * r), fmt(r), fmt(r), fmt(-2.0 * r))
}

fn rect_path(x: f64, y: f64, w: f64, h: f64) -> String {
    format!("M{} {} H{} V{} H{} Z", fmt(x), fmt(y), fmt(x + w), fmt(y + h), fmt(x))
}

fn rounded_rect_path(x: f64, y: f64, w: f64, h: f64, rx: f64, ry: f64) -> Result<String> {
    if rx < 0.0 || ry < 0.0 || 2.0 * rx > w || 2.0 * ry > h {
        bail!("rect radii ({rx}, {ry}) do not fit its size ({w} x {h})");
    }
    let arc = |sx: f64, sy: f64| format!("A{} {} 0 0 1 {} {}", fmt(rx), fmt(ry), fmt(sx), fmt(sy));
    Ok(format!(
        "M{} {} H{} {} V{} {} H{} {} V{} {} Z",
        fmt(x + rx),
        fmt(y),
        fmt(x + w - rx),
        arc(x + w, y + ry),
        fmt(y + h - ry),
        arc(x + w - rx, y + h),
        fmt(x + rx),
        arc(x, y + h - ry),
        fmt(y + ry),
        arc(x + rx, y)
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_lucide_style_icon_converts_to_per_element_path_data() {
        let svg = r#"<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M5 12h14"/><path d="m12 5 7 7-7 7"/></svg>"#;
        let data = icon_path_data(svg).expect("converts");
        // One string per source `<path>`: joining them would rebase the second path's
        // relative `m` onto the end of the first (31,17) instead of (12,5).
        assert_eq!(data, vec!["M5 12h14".to_string(), "m12 5 7 7-7 7".to_string()]);
    }

    #[test]
    fn circle_rect_and_polygon_translate() {
        let svg = r#"<svg><circle cx="12" cy="12" r="4"/><rect x="2" y="2" width="8" height="6" rx="1"/><polygon points="1,1 3,1 2,3"/></svg>"#;
        let data = icon_path_data(svg).expect("converts");
        assert!(data[0].starts_with("M8 12 a4 4 0 1 0 8 0"), "{data:?}");
        assert!(data[1].contains("A1 1 0 0 1"), "{data:?}");
        assert!(data[2].ends_with("M1 1 L3 1 L2 3 Z"), "{data:?}");
    }

    #[test]
    fn unknown_elements_are_rejected_not_dropped() {
        let svg = r#"<svg><image href="x.png"/></svg>"#;
        assert!(icon_path_data(svg).is_err());
        let empty = r#"<svg><desc>nothing</desc></svg>"#;
        assert!(icon_path_data(empty).is_err());
    }
}
